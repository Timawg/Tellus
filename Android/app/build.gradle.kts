// The bundled datasets are generated by the scripts in `scripts/` and live in
// the iOS tree. Copy them into the APK's assets at build time so there is a
// single source of truth and the iOS project stays untouched.
abstract class CopyBundledData : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val sources: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun copy() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        out.mkdirs()
        sources.forEach { it.copyTo(File(out, it.name)) }
    }
}

val iosFeatures = rootProject.layout.projectDirectory.dir("../iOS/Tellus/Features")
val copyBundledData = tasks.register<CopyBundledData>("copyBundledData") {
    sources.from(
        iosFeatures.file("Countries/Resources/country-borders.geojson"),
        iosFeatures.file("CountryGuide/DemocracySafety/vdem-democracy.json"),
    )
    outputDir.set(layout.buildDirectory.dir("generated/bundledData"))
}

androidComponents {
    onVariants { variant ->
        variant.sources.assets?.addGeneratedSourceDirectory(copyBundledData, CopyBundledData::outputDir)
    }
}

